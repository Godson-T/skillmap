// Framework-agnostic /api/analyze handler. Adapters:
//   - api/analyze.js      (Vercel serverless function)
//   - vite.config.js      (local dev middleware)
// Both call handleAnalyze() with the same deps, so dev and prod cannot drift.

import { randomUUID } from 'node:crypto';
import { AppError, errorBody } from './errors.js';
import { MAX_BODY_BYTES, resolveCors } from './http.js';
import { generateReport, llmConfig } from './llm.js';
import { createLogger } from './log.js';
import { PROMPT_VERSION } from './prompt.js';
import { createRateLimiter } from './rateLimit.js';
import { AnalyzeInput, formatIssues, goalKind } from './schema.js';

export const DISCLAIMER = 'AI estimate: generated by a language model from your inputs, not from live job-market data. Use it as a starting point, not a forecast.';

/** Build long-lived dependencies once per process / warm serverless instance. */
export function createDeps(env = process.env, overrides = {}) {
  const logger = overrides.logger ?? createLogger();
  const fetchImpl = overrides.fetchImpl ?? globalThis.fetch;
  return {
    env,
    logger,
    fetchImpl,
    rateLimiter: overrides.rateLimiter ?? createRateLimiter(env, { fetchImpl, logger }),
    now: overrides.now ?? Date.now,
    randomId: overrides.randomId ?? randomUUID,
  };
}

/**
 * @param {{ method: string, headers: Record<string,string>, body: unknown, ip: string, bodyTooLarge?: boolean }} req
 * @param {ReturnType<typeof createDeps>} deps
 * @returns {Promise<{ status: number, headers: Record<string,string>, body?: unknown }>}
 */
export async function handleAnalyze(req, deps) {
  const { env, logger, fetchImpl, rateLimiter, now, randomId } = deps;
  const requestId = randomId();
  const started = now();
  const cors = resolveCors(req.headers, env);
  const baseHeaders = { ...cors.headers, 'Content-Type': 'application/json', 'Cache-Control': 'no-store', 'X-Request-Id': requestId };
  const logFields = { requestId, method: req.method, model: llmConfig(env).model, promptVersion: PROMPT_VERSION, rateLimitBackend: rateLimiter.backend };

  const finish = (status, body, extra = {}) => {
    const level = status >= 500 ? 'error' : status >= 400 ? 'warn' : 'info';
    logger(level, 'analyze', { ...logFields, ...extra, status, latencyMs: now() - started });
    return { status, headers: { ...baseHeaders, ...(extra.retryAfter ? { 'Retry-After': String(extra.retryAfter) } : {}) }, body };
  };
  const fail = (err, extra = {}) => {
    const e = err instanceof AppError ? err : new AppError('INTERNAL', { detail: String(err?.message || err) });
    return finish(e.status, errorBody(e, requestId), {
      ...extra,
      code: e.code,
      detail: e.detail,
      retryAfter: e.retryAfter,
      attempts: err?.attempts,
      ...(err?.usage ? { promptTokens: err.usage.prompt, completionTokens: err.usage.completion, totalTokens: err.usage.total } : {}),
    });
  };

  try {
    if (req.method === 'OPTIONS') {
      if (!cors.allowed) return fail(new AppError('ORIGIN_NOT_ALLOWED'));
      return finish(204, undefined);
    }
    if (req.method !== 'POST') return fail(new AppError('METHOD_NOT_ALLOWED'));
    if (!cors.allowed) return fail(new AppError('ORIGIN_NOT_ALLOWED'));
    if (req.bodyTooLarge) return fail(new AppError('PAYLOAD_TOO_LARGE'));

    let body = req.body;
    if (typeof body === 'string' || Buffer.isBuffer(body)) {
      const raw = String(body);
      if (Buffer.byteLength(raw) > MAX_BODY_BYTES) return fail(new AppError('PAYLOAD_TOO_LARGE'));
      try { body = raw ? JSON.parse(raw) : {}; } catch { return fail(new AppError('INVALID_JSON')); }
    }
    if (!body || typeof body !== 'object' || Array.isArray(body)) return fail(new AppError('INVALID_JSON'));

    const parsed = AnalyzeInput.safeParse(body);
    if (!parsed.success) return fail(new AppError('INVALID_INPUT', { issues: formatIssues(parsed.error) }));
    const input = parsed.data;
    const inputFields = { skillsCount: input.skills.length, location: input.location, goalKind: goalKind(input.goal) };

    if (!env.GROQ_API_KEY) return fail(new AppError('SERVICE_UNAVAILABLE', { detail: 'GROQ_API_KEY missing' }), inputFields);

    const limit = await rateLimiter.check(req.ip, now());
    if (!limit.ok) return fail(new AppError(limit.code, { retryAfter: limit.retryAfter }), inputFields);

    const { report, model, attempts, usage } = await generateReport({ input, env, fetchImpl });
    return finish(200, {
      requestId,
      report,
      meta: { model, promptVersion: PROMPT_VERSION, generatedAt: new Date(now()).toISOString(), estimate: true, disclaimer: DISCLAIMER },
    }, { ...inputFields, attempts, promptTokens: usage.prompt, completionTokens: usage.completion, totalTokens: usage.total });
  } catch (err) {
    return fail(err);
  }
}
