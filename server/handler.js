// Framework-agnostic API handlers. Adapters:
//   - api/analyze.js, api/market.js  (Vercel serverless functions)
//   - vite.config.js                 (local dev / preview middleware)
// All call the handlers below with the same deps, so dev and prod cannot drift.

import { randomUUID } from 'node:crypto';
import { AppError, errorBody } from './errors.js';
import { MAX_BODY_BYTES, resolveCors } from './http.js';
import { generateReport, llmConfig } from './llm.js';
import { createLogger } from './log.js';
import { createMarketService } from './market/service.js';
import { PROMPT_VERSION } from './prompt.js';
import { createRateLimiter } from './rateLimit.js';
import { AnalyzeInput, MarketInput, formatIssues, goalKind } from './schema.js';

export const DISCLAIMER = 'AI estimate: generated by a language model from your inputs, not from live job-market data. Use it as a starting point, not a forecast.';

/** Build long-lived dependencies once per process / warm serverless instance. */
export function createDeps(env = process.env, overrides = {}) {
  const logger = overrides.logger ?? createLogger();
  const fetchImpl = overrides.fetchImpl ?? globalThis.fetch;
  return {
    env,
    logger,
    fetchImpl,
    rateLimiter: overrides.rateLimiter ?? createRateLimiter(env, { fetchImpl, logger }),
    market: overrides.market ?? createMarketService({ fetchImpl: overrides.marketFetchImpl ?? fetchImpl, logger }),
    now: overrides.now ?? Date.now,
    randomId: overrides.randomId ?? randomUUID,
  };
}

/**
 * Shared request pipeline: CORS -> method -> body size/JSON -> schema -> run.
 * @param {{ event: string, schema: import('zod').ZodTypeAny, logFields?: (input: any) => object,
 *           run: (input: any, ctx: { deps: any, req: any, requestId: string }) => Promise<{ body: object, log?: object }> }} spec
 */
function endpoint(spec) {
  return async function handle(req, deps) {
    const { env, logger, rateLimiter, now, randomId } = deps;
    const requestId = randomId();
    const started = now();
    const cors = resolveCors(req.headers, env);
    const baseHeaders = { ...cors.headers, 'Content-Type': 'application/json', 'Cache-Control': 'no-store', 'X-Request-Id': requestId };
    const logFields = { requestId, method: req.method, rateLimitBackend: rateLimiter.backend, ...(spec.baseLog?.(env) ?? {}) };

    const finish = (status, body, extra = {}) => {
      const level = status >= 500 ? 'error' : status >= 400 ? 'warn' : 'info';
      logger(level, spec.event, { ...logFields, ...extra, status, latencyMs: now() - started });
      return { status, headers: { ...baseHeaders, ...(extra.retryAfter ? { 'Retry-After': String(extra.retryAfter) } : {}) }, body };
    };
    const fail = (err, extra = {}) => {
      // Unknown errors log their type only: messages can embed input, headers or URLs.
      const e = err instanceof AppError ? err : new AppError('INTERNAL', { detail: `unhandled ${err?.name || typeof err}` });
      return finish(e.status, errorBody(e, requestId), {
        ...extra,
        code: e.code,
        detail: e.detail,
        retryAfter: e.retryAfter,
        attempts: err?.attempts,
        ...(err?.usage ? { promptTokens: err.usage.prompt, completionTokens: err.usage.completion, totalTokens: err.usage.total } : {}),
      });
    };

    let inputFields = {};
    try {
      if (req.method === 'OPTIONS') {
        if (!cors.allowed) return fail(new AppError('ORIGIN_NOT_ALLOWED'));
        return finish(204, undefined);
      }
      if (req.method !== 'POST') return fail(new AppError('METHOD_NOT_ALLOWED'));
      if (!cors.allowed) return fail(new AppError('ORIGIN_NOT_ALLOWED'));
      if (req.bodyTooLarge) return fail(new AppError('PAYLOAD_TOO_LARGE'));

      let body = req.body;
      if (typeof body === 'string' || Buffer.isBuffer(body)) {
        const raw = String(body);
        if (Buffer.byteLength(raw) > MAX_BODY_BYTES) return fail(new AppError('PAYLOAD_TOO_LARGE'));
        try { body = raw ? JSON.parse(raw) : {}; } catch { return fail(new AppError('INVALID_JSON')); }
      }
      if (!body || typeof body !== 'object' || Array.isArray(body)) return fail(new AppError('INVALID_JSON'));

      const parsed = spec.schema.safeParse(body);
      if (!parsed.success) return fail(new AppError('INVALID_INPUT', { issues: formatIssues(parsed.error) }));
      inputFields = spec.logFields?.(parsed.data) ?? {};

      const { body: out, log } = await spec.run(parsed.data, { deps, req, requestId });
      return finish(200, { requestId, ...out }, { ...inputFields, ...log });
    } catch (err) {
      return fail(err, inputFields);
    }
  };
}

export const handleAnalyze = endpoint({
  event: 'analyze',
  schema: AnalyzeInput,
  baseLog: (env) => ({ model: llmConfig(env).model, promptVersion: PROMPT_VERSION }),
  logFields: (input) => ({ skillsCount: input.skills.length, location: input.location, goalKind: goalKind(input.goal) }),
  async run(input, { deps, req }) {
    const { env, fetchImpl, rateLimiter, now } = deps;
    if (!env.GROQ_API_KEY) throw new AppError('SERVICE_UNAVAILABLE', { detail: 'GROQ_API_KEY missing' });

    const limit = await rateLimiter.check(req.ip, now());
    if (!limit.ok) throw new AppError(limit.code, { retryAfter: limit.retryAfter });

    const { report, model, attempts, usage } = await generateReport({ input, env, fetchImpl });
    return {
      body: {
        report,
        meta: { model, promptVersion: PROMPT_VERSION, generatedAt: new Date(now()).toISOString(), estimate: true, disclaimer: DISCLAIMER },
      },
      log: { attempts, promptTokens: usage.prompt, completionTokens: usage.completion, totalTokens: usage.total },
    };
  },
});

export const handleMarket = endpoint({
  event: 'market',
  schema: MarketInput,
  logFields: (input) => ({ location: input.location, goalKind: goalKind(input.goal) }),
  async run(input, { deps, req }) {
    const { rateLimiter, market, now } = deps;
    const cfg = rateLimiter.config ?? {};
    const limit = await rateLimiter.check(req.ip, now(), {
      scope: 'mk', perMinute: cfg.marketPerMinute, perDay: cfg.marketPerDay, countGlobal: false,
    });
    if (!limit.ok) throw new AppError(limit.code === 'GLOBAL_DAILY_CAP' ? 'RATE_LIMITED' : limit.code, { retryAfter: limit.retryAfter });

    const result = await market.skillDemand(input, now());
    if (result.boards.ok === 0) throw new AppError('UPSTREAM_ERROR', { detail: 'all job boards failed' });
    // Postings matched but none could be read: an upstream failure, not "no postings".
    if (result.matched > 0 && result.sampleSize === 0) {
      throw new AppError('UPSTREAM_ERROR', { detail: `all ${result.matched} posting detail fetches failed` });
    }
    return {
      body: { market: result },
      log: { sampleSize: result.sampleSize, scope: result.scope, boardsOk: result.boards.ok, detailsFailed: result.detailsFailed, degraded: result.degraded, cached: Boolean(result.cached) },
    };
  },
});
